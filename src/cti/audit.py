"""Hand-audit samples: write them without ever clobbering a filled-in audit, and score them.

Each sample row is a random matched transaction with a link to the source document. The auditor
fills `audit_correct` with y or n (the ticker we priced belongs to the company named in the filing,
at the trade date) and optionally `audit_note`. `cti audit score` reports accuracy with a 95%
Wilson interval.
"""

from __future__ import annotations

import math
from pathlib import Path

import pandas as pd

from cti.config import REPORTS_DIR

AUDIT_DIR = REPORTS_DIR / "audit"
FILES = {"insider": "match_audit_sample.csv", "congress": "congress_match_audit_sample.csv"}


def sec_filing_url(accession: str, cik: str) -> str:
    return f"https://www.sec.gov/Archives/edgar/data/{int(cik)}/{accession.replace('-', '')}/"


def house_ptr_url(doc_id: str, year: int) -> str:
    return f"https://disclosures-clerk.house.gov/public_disc/ptr-pdfs/{year}/{doc_id}.pdf"


def is_started(path: Path) -> bool:
    if not path.exists():
        return False
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    return "audit_correct" in df and df["audit_correct"].str.strip().ne("").any()


def write_sample(df: pd.DataFrame, path: Path) -> Path:
    """Write the sample unless an audit is already in progress there; then write *_new.csv instead."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if is_started(path):
        path = path.with_name(path.stem + "_new.csv")
    df.assign(audit_correct="", audit_note="").to_csv(path, index=False)
    return path


def wilson(k: int, n: int, z: float = 1.959964) -> tuple[float, float]:
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - h) / d, (c + h) / d)


def score(audit_dir: Path = AUDIT_DIR) -> pd.DataFrame:
    rows = []
    for group, name in FILES.items():
        p = audit_dir / name
        if not p.exists():
            continue
        a = pd.read_csv(p, dtype=str, keep_default_na=False)["audit_correct"].str.strip().str.lower()
        done = a[a.isin(["y", "n", "yes", "no"])]
        k, n = int(done.isin(["y", "yes"]).sum()), len(done)
        lo, hi = wilson(k, n)
        rows.append({"group": group, "audited": n, "of": len(a), "correct": k,
                     "accuracy": k / n if n else float("nan"), "ci_low": lo, "ci_high": hi})
    out = pd.DataFrame(rows)
    lines = ["# Hand-audit results (generated by `cti audit score`)", "",
             "| group | audited | correct | accuracy | 95% CI (Wilson) |", "|---|---:|---:|---:|---|"]
    for r in out.itertuples():
        acc = "n/a" if r.audited == 0 else f"{r.accuracy:.0%}"
        ci = "n/a" if r.audited == 0 else f"{r.ci_low:.0%} to {r.ci_high:.0%}"
        lines.append(f"| {r.group} | {r.audited} of {r.of} | {r.correct} | {acc} | {ci} |")
    (audit_dir / "AUDIT_RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
